/** `bangs` and `wispy-bangs` reuse the long mass rather than duplicating it. */
export function resolveShape(id) {
  const shape = HAIR_SHAPES[id] || HAIR_SHAPES['long-straight'];
  if (!shape.inherit) return shape;
  const base = HAIR_SHAPES[shape.inherit];
  return { ...base, ...shape, inherit: undefined };
}
